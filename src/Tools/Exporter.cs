using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Web.Script.Serialization;

namespace Simplemize
{
    /// <summary>Writes the catalog as JSON for the website, so the site always describes exactly what the app does.</summary>
    public static class Exporter
    {
        public static int Export(IList<Tweak> catalog, string file)
        {
            var list = new List<Dictionary<string, object>>();
            foreach (var t in catalog)
            {
                var changes = t.Actions.Select(a => a.Describe()).Select(d => new Dictionary<string, object> { ["where"] = d.Where, ["what"] = d.What }).ToList();

                // Keep machine-specific details (adapter IDs, RAM size, user paths) out of the public file.
                if (t.Id == "net.nagle")
                    changes = new List<Dictionary<string, object>>
                    {
                        new Dictionary<string, object> { ["where"] = @"HKLM\SYSTEM\CurrentControlSet\Services\Tcpip\Parameters\Interfaces\{each connected adapter}", ["what"] = "TcpAckFrequency = 1    (Windows default: not set)" },
                        new Dictionary<string, object> { ["where"] = @"HKLM\SYSTEM\CurrentControlSet\Services\Tcpip\Parameters\Interfaces\{each connected adapter}", ["what"] = "TCPNoDelay = 1    (Windows default: not set)" },
                    };
                if (t.Id == "svc.grouping")
                    changes = new List<Dictionary<string, object>>
                    {
                        new Dictionary<string, object> { ["where"] = @"HKLM\SYSTEM\CurrentControlSet\Control", ["what"] = "SvcHostSplitThresholdInKB = your memory size in KB    (Windows default: 3670016, i.e. 3.5 GB)" },
                    };
                if (t.Id == "clean.temp")
                    changes = new List<Dictionary<string, object>>
                    {
                        new Dictionary<string, object> { ["where"] = @"%TEMP%", ["what"] = "delete files older than 24 hours" },
                        new Dictionary<string, object> { ["where"] = @"C:\Windows\Temp", ["what"] = "delete files older than 24 hours" },
                    };
                if (t.Id == "clean.reports")
                    changes = new List<Dictionary<string, object>>
                    {
                        new Dictionary<string, object> { ["where"] = @"C:\ProgramData\Microsoft\Windows\WER\ReportArchive  ·  ReportQueue  ·  %LOCALAPPDATA%\CrashDumps", ["what"] = "delete all files" },
                    };

                var after = new List<string>();
                if (t.After.HasFlag(After.Restart)) after.Add("restart");
                if (t.After.HasFlag(After.SignOut)) after.Add("sign out");
                if (t.After.HasFlag(After.Explorer)) after.Add("explorer");
                var presets = new List<string>();
                if (t.Presets.HasFlag(Preset.Light)) presets.Add("light");
                if (t.Presets.HasFlag(Preset.Gamer)) presets.Add("gamer");
                if (t.Presets.HasFlag(Preset.Stripped)) presets.Add("stripped");

                list.Add(new Dictionary<string, object>
                {
                    ["id"] = t.Id,
                    ["section"] = t.Section.ToString(),
                    ["group"] = t.Group,
                    ["level"] = t.Level == Level.Heavy ? "heavy" : "minor",
                    ["title"] = t.Title,
                    ["summary"] = t.Summary,
                    ["gain"] = t.Gain,
                    ["tradeoff"] = t.TradeOff,
                    ["undo"] = t.UndoText,
                    ["affects"] = t.Affects,
                    ["after"] = after,
                    ["presets"] = presets,
                    ["revertible"] = t.Revertible,
                    ["oneShot"] = t.OneShot,
                    ["security"] = t.Security,
                    ["requires"] = t.Requires,
                    ["changes"] = changes,
                });
            }
            var json = new JavaScriptSerializer { MaxJsonLength = int.MaxValue }.Serialize(new Dictionary<string, object>
            {
                ["version"] = Ui.MainWindow.Version,
                ["tweaks"] = list,
            });
            // A .js file works when the site is opened straight from disk (no fetch needed).
            if (file.EndsWith(".js", StringComparison.OrdinalIgnoreCase))
                json = "// Generated by Simplemize.exe --export. Do not edit by hand.\nwindow.SIMPLEMIZE = " + json + ";\n";
            File.WriteAllText(file, json, new UTF8Encoding(false));
            return 0;
        }
    }
}
